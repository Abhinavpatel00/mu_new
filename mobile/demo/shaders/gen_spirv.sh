#!/bin/sh
# GLSL -> SPIR-V -> a C header. Vulkan 1.1 core, no extensions: the shaders
# compile for every device in the Android Baseline 2021 fleet.
#
# Two sets. The scene set, and a MIRROR set for the reflection pass: the same
# source with -DMIRROR=1, where the vertex shaders flip world y about the water
# plane. One shader source, two pipelines, no second material system.
set -e
GLSLC=${GLSLC:-$(ls "$ANDROID_HOME"/ndk/*/shader-tools/linux-x86_64/glslc | head -1)}
GLSLC=${GLSLC:-glslc}
cd "$(dirname "$0")"

SHADERS="composite.vert composite.frag sky.vert sky.frag terrain.vert terrain.frag \
         prop.vert prop.frag grass.vert grass.frag water.vert water.frag \
         creature.vert creature.frag hud.vert hud.frag"

# everything the reflection pass draws, with the water plane flip compiled in
MIRRORED="sky.vert sky.frag terrain.vert terrain.frag prop.vert prop.frag \
          grass.vert grass.frag creature.vert creature.frag"

for n in $SHADERS; do
  $GLSLC --target-env=vulkan1.1 -O -o /tmp/$n.spv $n
done
for n in $MIRRORED; do
  $GLSLC --target-env=vulkan1.1 -DMIRROR=1 -O -o /tmp/$n.mirror.spv $n
done

emit() {  # emit <array-name> <spv-file>
  echo "static const uint32_t $1[] = {"
  od -An -v -tu4 "$2" | tr -s ' ' | sed 's/^ //' | awk '{for(i=1;i<=NF;i++) printf "%s,", $i; printf "\n"}'
  echo "};"
}

{
  echo "// generated by shaders/gen_spirv.sh -- do not edit"
  echo "#pragma once"
  echo "#include <stdint.h>"
  for n in $SHADERS; do
    emit "spirv_$(echo "$n" | tr '.' '_')" "/tmp/$n.spv"
  done
  for n in $MIRRORED; do
    emit "spirv_$(echo "$n" | tr '.' '_')_mirror" "/tmp/$n.mirror.spv"
  done
} > spirv.h
wc -c spirv.h
